class Dialog:
    """아주 작은 대화 상태 기계. 기분 토로 -> 이유 묻기 -> 공감 + 되묻기 -> 마무리."""

    def __init__(self):
        self.stage = 0  # 0 없음, 1 이유 물어봄, 2 공감함
        self.turns = 0

    def reply(self, text: str, name: str) -> str | None:
        compact = text.replace(" ", "")
        if self.stage == 0:
            if any(w.replace(" ", "") in compact for w in MOOD_WORDS):
                self.stage, self.turns = 1, 0
                return random.choice(ASK_REASON)
            return None
        self.turns += 1
        if self.stage == 1:
            for keys, empath, follow in REASONS:
                if any(k.replace(" ", "") in compact for k in keys):
                    self.stage = 2
                    return random.choice(empath) + " " + random.choice(follow)
            self.stage = 2
            return random.choice(GENERIC_REASON[0]) + " " + random.choice(GENERIC_REASON[1])
        if self.stage == 2:
            self.stage, self.turns = 0, 0
            if any(w in compact for w in BETTER_WORDS):
                return random.choice(("다행이다냥. 언제든 또 말해.", "그래, 그거면 됐어. 냥.", "잘했어. 오늘 남은 시간은 가볍게 가자, 냥."))
            return random.choice(CLOSERS)
        return None


_dialog = Dialog()


def answer(text: str, name: str = "먹물") -> str:
    t = re.sub(r"\s+", " ", text.strip().lower())
    compact = t.replace(" ", "")
    flow = _dialog.reply(t, name)
    if flow:
        return _fill(flow, name)
    for keys, replies in RULES:
        for k in keys:
            if k.replace(" ", "") in compact:
                return _fill(random.choice(replies), name)
    return _fill(random.choice(FALLBACK), name)
