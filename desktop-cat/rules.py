def _fill(text: str, name: str) -> str:
    now = _dt.datetime.now()
    days = "월화수목금토일"
    return text.format(
        name=name,
        time=now.strftime("%H시 %M분"),
        date=f"{now.month}월 {now.day}일 {days[now.weekday()]}요일",
    )


def answer(text: str, name: str = "먹물") -> str:
    t = re.sub(r"\s+", " ", text.strip().lower())
    compact = t.replace(" ", "")
    for keys, replies in RULES:
        for k in keys:
            if k.replace(" ", "") in compact:
                return _fill(random.choice(replies), name)
    return _fill(random.choice(FALLBACK), name)
