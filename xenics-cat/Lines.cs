        static readonly string[] Closers = { "말해줘서 고마워, 냥. 혼자 끙끙대는 것보다 훨씬 나아.", "오늘은 여기까지만 생각하자. 나머지는 내일의 너한테 맡겨, 냥.", "힘들면 쉬어~ 냥. 세상은 안 무너져.", "오늘 소주 한잔 할거냥? 아니면 따뜻한 차도 좋고.", "기분 전환할래? 창밖 한 번 보고, 물 한 잔 마시자, 냥." };
        static readonly string[] Better = { "괜찮아", "좀 나아", "나아졌", "고마워", "풀렸", "됐어", "ㅇㅇ", "응" };
        static readonly string[] Relief = { "다행이다냥. 언제든 또 말해.", "그래, 그거면 됐어. 냥.", "잘했어. 오늘 남은 시간은 가볍게 가자, 냥." };

        static int stage = 0; // 0 없음, 1 이유 물어봄, 2 공감함

        public static string Reply(string text, string name, string tone)
        {
            string t = Regex.Replace(text.Trim(), @"\s+", " ");
            string compact = t.Replace(" ", "").ToLowerInvariant();
            string outp = null;

            if (stage == 0 && Mood.Any(w => compact.Contains(w.Replace(" ", ""))))
            { stage = 1; outp = Pick(AskReason); }
            else if (stage == 1)
            {
                stage = 2;
                var hit = Reasons.FirstOrDefault(r => r.Item1.Any(k => compact.Contains(k.Replace(" ", ""))));
                outp = hit != null ? Pick(hit.Item2) + " " + Pick(hit.Item3) : Pick(GenericEmpath) + " " + Pick(GenericFollow);
            }
            else if (stage == 2)
            {
                stage = 0;
                outp = Better.Any(w => compact.Contains(w)) ? Pick(Relief) : Pick(Closers);
            }
            if (outp == null)
            {
                foreach (var rule in Rules)
                    if (rule.Key.Any(k => compact.Contains(k.Replace(" ", "")))) { outp = Pick(rule.Value); break; }
            }
            if (outp == null) outp = Pick(Fallback);
            return Style(Fill(outp, name), tone);
        }

        static string Fill(string s, string name)
        {
            var now = DateTime.Now; string days = "월화수목금토일";
            return s.Replace("{name}", name).Replace("{time}", now.ToString("HH시 mm분"))
                    .Replace("{date}", now.Month + "월 " + now.Day + "일 " + days[((int)now.DayOfWeek + 6) % 7] + "요일");
        }

        /// <summary>성장 단계별 말투. 아기는 혀 짧은 소리, 어린이는 신남.</summary>
        public static string Style(string text, string tone)
        {
            if (tone == "baby") return text.Replace("냐옹", "미야옹").Replace("냥!", "냐앙!").Replace("냥.", "냐앙.").Replace("냥?", "냐앙?").Replace(", 냥", ", 냐앙");
            if (tone == "kid") return text.Replace("냐옹", "냐옹!").Replace("냥.", "냥!");
            return text;
        }
    }
